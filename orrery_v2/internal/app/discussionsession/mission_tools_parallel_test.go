func TestMissionToolApplierPlansCoordinatorParallelLanesIntoMissionTasks(t *testing.T) {
	missions := &capturingMissionCommands{}
	applier := NewMissionToolApplier(missions)

	calls := []ToolCallResult{{
		Name: "mission_coordinator_plan_parallel",
		Arguments: map[string]string{
			"mission_id":        "mission-1",
			"mission_task_id":   "task-root",
			"goal":              "Ship discussion streaming and debug visibility",
			"join_condition":    "Both lanes finish and provide evidence before the lead agent reports delivery.",
			"idempotency_key":   "parallel-plan-1",
			"worker_lanes_json": `[{"role":"backend coder","agent_id":"agent-backend","scope":"Wire discussion stream events and tool application","ownership":"orrery_v2/internal/app/discussionsession","acceptance_criteria":["Discussion stream emits report patches"],"required_evidence":["go test ./internal/app/discussionsession"],"idempotency_key":"lane-backend"},{"role":"frontend coder","assignee_id":"agent-frontend","scope":"Render discussion stream and prompt debug","ownership":"orrery_v2/web/src/lib/components/discussions","acceptance_criteria":["Discussion panel renders stream output"],"required_evidence":["npm test -- --run src/lib/components/discussions/DiscussionPanel.test.ts"],"idempotency_key":"lane-frontend"}]`,
		},
	}}
	_, err := applier.Apply(context.Background(), missionToolTestViewer(), "conv-1", calls)
	if err != nil {
		t.Fatal(err)
	}

	if len(missions.createTaskCalls) != 2 {
		t.Fatalf("created task calls = %+v", missions.createTaskCalls)
	}
	if missions.createTaskCalls[0].MissionID != missioncore.MissionID("mission-1") || missions.createTaskCalls[0].Goal != "backend coder: Wire discussion stream events and tool application" {
		t.Fatalf("first lane task = %+v", missions.createTaskCalls[0])
	}
	if !missions.createTaskCalls[0].TaskID.IsZero() {
		t.Fatalf("new lane task id should be generated by backend, got %q", missions.createTaskCalls[0].TaskID)
	}
	if !strings.Contains(missions.createTaskCalls[0].Scope, "Wire discussion stream events and tool application") || !strings.Contains(missions.createTaskCalls[0].Scope, "Parent Mission Task: task-root") {
		t.Fatalf("first lane scope = %q", missions.createTaskCalls[0].Scope)
	}
	if len(missions.createTaskCalls[0].ExpectedDeliverables) != 1 || missions.createTaskCalls[0].ExpectedDeliverables[0].Title != "backend coder: Wire discussion stream events and tool application" {
		t.Fatalf("first lane deliverables = %+v", missions.createTaskCalls[0].ExpectedDeliverables)
	}
	if len(missions.createTaskCalls[0].AcceptanceCriteria) != 1 || missions.createTaskCalls[0].AcceptanceCriteria[0] != "Discussion stream emits report patches" {
		t.Fatalf("first lane acceptance criteria = %+v", missions.createTaskCalls[0].AcceptanceCriteria)
	}
	if len(missions.createTaskCalls[0].EvidenceRequirements) != 1 || missions.createTaskCalls[0].EvidenceRequirements[0].Description != "go test ./internal/app/discussionsession" || !missions.createTaskCalls[0].EvidenceRequirements[0].Required {
		t.Fatalf("first lane evidence requirements = %+v", missions.createTaskCalls[0].EvidenceRequirements)
	}
	if len(missions.assignCalls) != 2 {
		t.Fatalf("assign calls = %+v", missions.assignCalls)
	}
	if missions.assignCalls[0].TaskID != missioncore.TaskID("task-1") || missions.assignCalls[0].AssigneeID != "agent-backend" {
		t.Fatalf("first lane assignment = %+v", missions.assignCalls[0])
	}
	if missions.assignCalls[1].TaskID != missioncore.TaskID("task-2") || missions.assignCalls[1].AssigneeID != "agent-frontend" {
		t.Fatalf("second lane assignment = %+v", missions.assignCalls[1])
	}
	if calls[0].Result["status"] != "planned" || calls[0].Result["task_ids"] != "task-1,task-2" {
		t.Fatalf("coordinator result = %+v", calls[0].Result)
	}
}

func TestMissionToolApplierStartsCoordinatorParallelLanes(t *testing.T) {
	missions := &capturingRunnableMissionCommands{capturingMissionCommands: &capturingMissionCommands{}}
	applier := NewMissionToolApplier(missions)
	calls := []ToolCallResult{{
		Name: "mission_coordinator_plan_parallel",
		Arguments: map[string]string{
			"mission_id": "mission-1", "mission_task_id": "task-root", "idempotency_key": "parallel-run",
			"worker_lanes_json": `[{"role":"researcher","agent_id":"agent-1","goal":"Gather evidence","runtime_kind":"codex"},{"role":"builder","agent_id":"agent-2","goal":"Build result"}]`,
		},
	}}

	ctx := withMissionToolParentRun(context.Background(), "responsibility-run-1")
	if _, err := applier.Apply(ctx, missionToolTestViewer(), "conv-1", calls); err != nil {
		t.Fatal(err)
	}
	if len(missions.startCalls) != 2 {
		t.Fatalf("started runs = %+v", missions.startCalls)
	}
	if missions.startCalls[0].TaskID != "task-1" || missions.startCalls[0].RuntimeKind != "codex" || missions.startCalls[0].QueueID != "mission:mission-1:agent:agent-1" {
		t.Fatalf("first started lane = %+v", missions.startCalls[0])
	}
	if missions.startCalls[1].TaskID != "task-2" || missions.startCalls[1].RuntimeKind != "pi" || missions.startCalls[1].QueueID != "mission:mission-1:agent:agent-2" {
		t.Fatalf("second started lane = %+v", missions.startCalls[1])
	}
	if missions.startCalls[0].ParentRunID != "responsibility-run-1" || missions.startCalls[1].ParentRunID != "responsibility-run-1" {
		t.Fatalf("parent run provenance = %+v", missions.startCalls)
	}
	if calls[0].Result["status"] != "accepted" || calls[0].Result["run_ids"] != "run-task-1,run-task-2" {
		t.Fatalf("coordinator result = %+v", calls[0].Result)
	}
}

func TestMissionToolApplierValidatesEveryCoordinatorLaneBeforeWriting(t *testing.T) {
	missions := &capturingMissionCommands{}
	applier := NewMissionToolApplier(missions)

	_, err := applier.Apply(context.Background(), missionToolTestViewer(), "conv-1", []ToolCallResult{{
		Name: "mission_coordinator_plan_parallel",
		Arguments: map[string]string{
			"mission_id":        "mission-1",
			"mission_task_id":   "task-root",
			"worker_lanes_json": `[{"role":"researcher","agent_id":"agent-1","goal":"Gather evidence"},{"role":"builder","goal":"Build result"}]`,
		},
	}})

	if err == nil || !strings.Contains(err.Error(), "lane 2 assignee_id is required") {
		t.Fatalf("error = %v, want second lane validation failure", err)
	}
	if len(missions.createTaskCalls) != 0 || len(missions.assignCalls) != 0 {
		t.Fatalf("coordinator plan wrote partial lanes: create=%+v assign=%+v", missions.createTaskCalls, missions.assignCalls)
	}
}

type capturingRunnableMissionCommands struct {
	*capturingMissionCommands
	startCalls []missioncontrol.StartAgentRunCommand
}

func (c *capturingRunnableMissionCommands) StartAgentRun(_ context.Context, _ missioncontrol.ViewerRef, command missioncontrol.StartAgentRunCommand) (missioncontrol.CommandReceiptDTO, error) {
	c.startCalls = append(c.startCalls, command)
	return missioncontrol.CommandReceiptDTO{CommandID: "run-" + command.TaskID.String(), Status: "accepted", MissionID: command.MissionID.String(), TaskID: command.TaskID.String()}, nil
}

