func DefaultActionType(id ActionTypeID) (ActionType, bool) {
	for _, actionType := range DefaultActionTypes() {
		if actionType.ID == id {
			return cloneActionType(actionType), true
		}
	}
	return ActionType{}, false
}

func InstallDefaultActionTypes(ctx context.Context, service *Service) error {
	if service == nil {
		return ErrInvalidRequest
	}
	for _, actionType := range DefaultActionTypes() {
		if err := service.RegisterActionType(ctx, actionType); err != nil && !errors.Is(err, ErrAlreadyExists) {
			return err
		}
	}
	return nil
}
