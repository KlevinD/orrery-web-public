import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

describe('memory center', () => {
  it('loads only the visible owner directory without reporting unloaded counts as zero', () => {
    const source = readFileSync('src/routes/resources/memory/+page.svelte', 'utf-8')
    expect(source).toContain("useOrgGraphQuery(() => ({}), () => owner === 'organization')")
    expect(source).toContain("limit: 1000 }), () => owner === 'agent')")
    expect(source).toContain('organizationQuery.data ?')
    expect(source).toContain('workforceQuery.data ?')
  })

  it('keeps the old memory redirect backed up but disabled', () => {
    const source = readFileSync('src/routes/memory/+page.ts', 'utf-8')

    expect(source).toContain('requireLegacyRouteAliases()')
    expect(source).toContain("'/resources/memory'")
  })

  it('presents memory by organization and agent while keeping profiles as settings', () => {
    const source = readFileSync('src/lib/components/memory/MemoryAdminWorkspace.svelte', 'utf-8')
    const center = readFileSync('src/routes/resources/memory/+page.svelte', 'utf-8')

    expect(source).toContain('groupMemoryDiaryRecords')
    expect(source).toContain("t('memory.diaryFiles')")
    expect(source).toContain("t('memory.dailyDiary')")
    expect(source).toContain("t('memory.viewRaw')")
    expect(source).toContain('memoryDiaryPath')
    expect(source).toContain('memoryDiaryDate')
    expect(source).toContain('MemoryCitationEvidenceList')
    expect(source).toContain('selectedRecord.citation_evidence')
    expect(source).toContain("t('memory.value.scope.agent')")
    expect(source).toContain('memoryValueLabel(record.lifecycle_status)')
    expect(source).toContain("grid grid-cols-2 gap-3 md:grid-cols-4")
    expect(source).toContain("activeMemoryView === 'diary' && diaryDays.length > 0")
    expect(source).toContain('mobileFiltersOpen')
    expect(source).toContain("t('memory.filters')")
    expect(source).toContain('embedded?: boolean')
    expect(center).toContain("type MemoryOwner = 'organization' | 'agent'")
    expect(center).toContain("t('resources.memory.organizationMemory')")
    expect(center).toContain("t('resources.memory.agentMemory')")
    expect(center).toContain("t('resources.memory.memorySettings')")
    expect(center).toContain("t('resources.memory.workMemories')")
    expect(center).toContain('groupProfiles(organizationProfiles')
    expect(center).toContain('useMemoryRecordsByProfilesQuery')
    expect(center).toContain('limit: RESOURCE_CATALOG_PAGE_SIZE')
    expect(center).toContain('subjects.find((subject) => subject.recordCount > 0)')
    expect(center).toContain("{subject.subtitle ? `${subject.subtitle} · ` : ''}{subject.recordCount}")
    expect(center).toContain('useSettingsQuery')
    expect(center).toContain('useMemoryProfileUpdateMutation')
    expect(center).toContain('data-memory-settings-message')
    expect(center).toContain('useOrgGraphQuery')
    expect(center).toContain('useWorkforceMembersQuery')
    expect(center).not.toContain('includeMembers: true')
    expect(center).toContain('includeDetails: false')
    expect(center).toContain("owner === 'agent' ? workforceQuery.isLoading : organizationQuery.isLoading")
    expect(center).toContain('memoryQuery.isLoading || directoryLoading')
    expect(center).toContain('WorkforceAvatar')
    expect(center).toContain('groupMemoryDiaryRecords')
    expect(center).toContain('data-memory-content-toolbar')
    expect(center).toContain('data-memory-diary')
    expect(center).toContain('data-memory-disabled')
    expect(center).toContain("t('resources.memory.searchContent')")
    expect(center).toContain("t('resources.memory.includeHistory')")
    expect(center).toContain('data-memory-settings')
    expect(center).toContain('data-memory-candidates')
    expect(center).toContain('data-memory-record-detail')
    expect(center).toContain('data-memory-record-trigger')
    expect(center).toContain('onclick={() => openMemoryDetail(record.memory_id)}')
    expect(center).toContain('naturalizeMemoryText')
    expect(center).toContain("t('resources.memory.repeatedFactsSummary'")
    expect(center).toContain("t('resources.memory.sourceExplanation'")
    expect(center).toContain("t('resources.memory.memoryDetail')")
    expect(center).not.toContain('MemoryCitationEvidenceList')
    expect(center).not.toContain("t('memory.viewRaw')")
    expect(center).not.toContain('memoryDiaryPath')
    expect(center).not.toContain("detailRow('memory.memoryId'")
    expect(center).not.toContain("detailRow('memory.profileId'")
    expect(center).not.toContain("detailRow('memory.candidateId'")
    expect(center).not.toContain('record.scope.id')
    expect(center).not.toContain('MemoryAdminWorkspace')
    expect(center).not.toContain('useMemoryDigestMutation')
    expect(center).not.toContain('usePersonalMemoryProfileQuery')
    expect(center).not.toContain("memoryKind === 'mission'")
    expect(center).not.toContain("memoryKind === 'project'")
    expect(center).not.toContain("memoryKind === 'discussion'")
  })
})
