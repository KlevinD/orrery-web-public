import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

describe('scheduled tasks page', () => {
  it('does not fetch task personnel or expose task refresh in the results view', () => {
    const source = readFileSync('src/routes/scheduled-tasks/+page.svelte', 'utf-8')
    const inbox = readFileSync('src/routes/scheduled-tasks/ScheduledRunInbox.svelte', 'utf-8')

    expect(source).toContain("() => workspaceView === 'tasks' || showEditor")
    expect(source).toMatch(/\{#if workspaceView === 'tasks'\}\s*<Button variant="outline" onclick=\{\(\) => \{ taskStatsQuery.refetch/)
    expect(inbox).toContain('onclick={() => inboxQuery.refetch()}')
  })

  it('uses unpaginated statistics with explicit loading and failure states', () => {
    const source = readFileSync('src/routes/scheduled-tasks/+page.svelte', 'utf-8')
    expect(source).toContain("useScheduledTaskStatsQuery(() => workspaceView === 'tasks')")
    expect(source).not.toContain('allTasksQuery')
    expect(source).toContain("summary?.total ?? '-'")
    expect(source).toContain('taskStatsQuery.isError')
    expect(source).toContain('最近一次运行（含归档）')
    expect(source).not.toContain('最近 7 天')
  })

  it('wires the scheduler page to task plans and the result inbox', () => {
    const source = readFileSync('src/routes/scheduled-tasks/+page.svelte', 'utf-8')

    expect(source).toContain('useScheduledTasksQuery')
    expect(source).toContain('useScheduledRunInboxQuery')
    expect(source).toContain("workspaceView = $state<'tasks' | 'results'>")
    expect(source).toContain('<ScheduledRunInbox')
    expect(source).toContain('mapScheduledTaskFormToPayload')
    expect(source).toContain('runNow')
  })

  it('implements the redesigned scheduler management layout and filters', () => {
    const source = readFileSync('src/routes/scheduled-tasks/+page.svelte', 'utf-8')
    const appShell = readFileSync('src/lib/components/layout/AppShell.svelte', 'utf-8')
    const shell = readFileSync('src/lib/i18n/locales/zh-CN/shell.ts', 'utf-8')
    const dialog = readFileSync('src/routes/scheduled-tasks/SchedulerTaskFormDialog.svelte', 'utf-8')

    expect(shell).toContain('"nav.scheduler": "自动化"')
    expect(source).toContain('自动化日程 / 执行计划')
    expect(source).toContain('自动化任务列表')
    expect(source).toContain('结果收件箱')
    expect(source).toContain('任务计划')
    expect(source).toContain('openRunHistory(task)')
    expect(source).toContain('查看结果报告：${displayTaskTitle(task)}')
    expect(source).toContain('Legacy modal report kept inactive during the inbox rollout')
    expect(source).toContain('新建自动化')
    expect(source).toContain('自动化任务已创建。')
    expect(source).toContain('grid grid-cols-2 gap-3 xl:grid-cols-4')
    expect(appShell).toContain("$page.url.pathname === '/scheduled-tasks'")
    expect(dialog).toContain("title={editing ? '编辑自动化任务' : '新建自动化任务'}")
    expect(dialog).toContain("{editing ? '保存' : '创建自动化任务'}")
    expect(source).toContain('timelineDays')
    expect(source).toContain('tasksForDay')
    expect(source).toContain('startOfLocalWeek')
    expect(source).toContain('expandOccurrences: true')
    expect(source).toContain('occurrenceTimezone: Intl.DateTimeFormat().resolvedOptions().timeZone')
    expect(source).toContain('selectedDayGanttItems')
    expect(source).toContain('layoutScheduledTasksForGantt')
    expect(source).toContain("scheduleView = $state<'schedule' | 'plan'>('schedule')")
    expect(source).toContain('data-schedule-timeline')
    expect(source).toContain('data-schedule-task-chip')
    expect(source).toContain('data-task-status={item.task.status}')
    expect(source).toContain('scheduleTaskClass(item.task, lane.executor)')
    expect(source).toContain("if (task.status === 'disabled') return 'border-zinc-200 bg-zinc-100 text-zinc-700 hover:border-zinc-300'")
    expect(source).toContain('selectedDayAgentLanes')
    expect(source).toContain('groupScheduledTasksByAgent')
    expect(source).toContain('data-agent-schedule-lane')
    expect(source).toContain('执行智能体 / 时间')
    expect(source).toContain('data-execution-plan')
    expect(source).toContain('data-execution-plan-row')
    expect(source).toContain('编辑任务：${displayTaskTitle(item.task)}')
    expect(source).toContain('searchTerm')
    expect(source).toContain('debouncedSearchTerm')
    expect(source).toContain('window.setTimeout')
    expect(source).toContain('statusFilter')
    expect(source).toContain('sortOrder')
    expect(source).toContain('pageSize')
    expect(source).toContain('goToPage')
    expect(source).not.toContain('目标 / 描述')
    const artifacts = readFileSync('src/routes/scheduled-tasks/ScheduledRunArtifacts.svelte', 'utf-8')
    expect(artifacts).toContain('schedulerApi.readRunArtifact')
    expect(artifacts).toContain('data-scheduled-run-artifacts')
    expect(artifacts).toContain('renderSafeMarkdown')
  })

  it('feeds strict selector options into the automation task form', () => {
    const source = readFileSync('src/routes/scheduled-tasks/+page.svelte', 'utf-8')
    const dialog = readFileSync('src/routes/scheduled-tasks/SchedulerTaskFormDialog.svelte', 'utf-8')

    expect(source).toContain('useDiscussionListQuery')
    expect(source).toContain('useWorkforceMembersQuery')
    expect(source).toContain('useResourceToolsInfiniteQuery')
    expect(source).toContain('() => showEditor')
    expect(source).toContain('includeDetails: false')
    expect(source).toContain('discussionOptions')
    expect(source).toContain('agentOptions')
    expect(source).toContain('memberOptions')
    expect(source).toContain('toolOptions')
    expect(source).not.toContain('useSettingsQuery')
    expect(source).not.toContain('useMissionListQuery')
    expect(source).not.toContain('useMissionTasksQuery')
    expect(source).not.toContain('runtimeOptions')
    expect(source).not.toContain('missionOptions')
    expect(source).not.toContain('taskOptions')
    expect(dialog).toContain('discussionOptions')
    expect(dialog).toContain('agentOptions')
    expect(dialog).toContain('memberOptions')
    expect(dialog).toContain('toolOptions')
    expect(dialog).not.toContain('runtimeOptions')
    expect(dialog).not.toContain('missionOptions')
    expect(dialog).not.toContain('taskOptions')
    expect(dialog).not.toContain('Mission（可选）')
    expect(dialog).not.toContain('Task（可选）')
    expect(dialog).not.toContain('Runtime（可选）')
    expect(dialog).toContain('允许自主加入成员')
    expect(dialog).toContain('初始成员')
    expect(dialog).toContain('调用工具 / MCP')
    expect(dialog).toContain('经验记忆提炼')
    expect(dialog).toContain('世界记忆整合')
    expect(dialog).toContain('记忆生命周期清理')
    expect(dialog).not.toContain('{field.description}')
  })

  it('opens exact run deep links and exposes Mission and Responsibility navigation', () => {
    const source = readFileSync('src/routes/scheduled-tasks/+page.svelte', 'utf-8')
    const inbox = readFileSync('src/routes/scheduled-tasks/ScheduledRunInbox.svelte', 'utf-8')

    expect(source).toContain("searchParams.get('task')")
    expect(source).toContain("searchParams.get('run')")
    expect(source).toContain("searchParams.get('view')")
    expect(source).toContain("searchParams.get('filter')")
    expect(inbox).toContain('runId: exactRunID')
    expect(inbox).toContain('data-scheduled-run-inbox-item')
    expect(inbox).toContain('`/missions/${encodeURIComponent(selectedItem.run.mission_id)}`')
    expect(inbox).toContain('`/responsibilities?responsibility=${encodeURIComponent(selectedItem.run.responsibility_id)}`')
  })

  it('renders responsibility reconciliation history without exposing it as a form target', () => {
    const source = readFileSync('src/routes/scheduled-tasks/ScheduledRunInbox.svelte', 'utf-8')
    const form = readFileSync('src/routes/scheduled-tasks/scheduledTaskForm.ts', 'utf-8')
    const dialog = readFileSync('src/routes/scheduled-tasks/SchedulerTaskFormDialog.svelte', 'utf-8')

    expect(source).toContain('selectedItem.run.responsibility_reconcile')
    expect(source).toContain('data-responsibility-reconcile-stats')
		expect(source).toContain('selectedItem.run.responsibility_evaluation')
		expect(source).toContain('data-responsibility-evaluation')
		expect(source).toContain('evaluation.decision_kind')
		expect(source).toContain('selectedItem.run.responsibility_evaluation_batch')
		expect(source).toContain('<ResponsibilityEvaluationBatch')
    expect(form).not.toContain("'responsibility_reconcile'")
    expect(dialog).not.toContain('responsibility_reconcile')
		expect(form).not.toContain("'responsibility_evaluation'")
		expect(dialog).not.toContain('responsibility_evaluation')
  })

  it('loads batched responsibility details only when expanded and uses cursor pagination', () => {
    const source = readFileSync('src/routes/scheduled-tasks/ResponsibilityEvaluationBatch.svelte', 'utf-8')

    expect(source).toContain('bind:open')
    expect(source).toContain('() => open')
    expect(source).toContain('useResponsibilityEvaluationItemsQuery')
    expect(source).toContain('next_cursor')
    expect(source).toContain('cursorStack')
    expect(source).toContain('data-responsibility-evaluation-item')
    expect(source).toContain('item.mission_id')
    expect(source).toContain('item.responsibility_id')
  })
})
